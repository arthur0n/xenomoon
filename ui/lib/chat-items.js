// One chat item from one main-conversation message, stored (.jsonl transcript
// entry) or live (SDK message), and the chat window size. Pure: loaded by the
// Node server and by the browser alike.

/** The number of chat items a session shows. */
export const CHAT_WINDOW = 50;

/**
 * The tags Claude Code wraps non-conversation user entries in (slash commands,
 * local command output, bash mode, reminders, task notifications).
 */
export const WRAPPER_TAGS = Object.freeze([
  "command-name",
  "command-message",
  "command-args",
  "local-command-stdout",
  "local-command-stderr",
  "local-command-caveat",
  "bash-input",
  "bash-stdout",
  "bash-stderr",
  "system-reminder",
  "task-notification",
]);

/** The opening of the caveat Claude Code writes before local command output. */
export const LOCAL_COMMAND_CAVEAT =
  "Caveat: The messages below were generated by the user while running local commands";

const WRAPPER_OPEN = new RegExp(`^<(?:${WRAPPER_TAGS.join("|")})[\\s>]`);

/**
 * A message in either form: a stored transcript entry (`isSidechain`, the
 * metadata flags) or a live SDK message (`parent_tool_use_id`, `isSynthetic`,
 * `isReplay`).
 * @typedef {object} ChatSource
 * @property {string} [type]
 * @property {boolean} [isSidechain]
 * @property {boolean} [isMeta]
 * @property {boolean} [isCompactSummary]
 * @property {boolean} [isVisibleInTranscriptOnly]
 * @property {string | null} [parent_tool_use_id]
 * @property {boolean} [isSynthetic]
 * @property {boolean} [isReplay]
 * @property {string} [uuid]
 * @property {string} [timestamp]
 * @property {{ content?: string | Array<{ type?: string, text?: string }> }} [message]
 */

/** @param {ChatSource} m @returns {boolean} */
function isMetadata(m) {
  return [
    m.isSidechain,
    m.parent_tool_use_id,
    m.isSynthetic,
    m.isReplay,
    m.isMeta,
    m.isCompactSummary,
    m.isVisibleInTranscriptOnly,
  ].some(Boolean);
}

/** @param {string} t @returns {boolean} */
function isUserWrapper(t) {
  return WRAPPER_OPEN.test(t) || t.startsWith(LOCAL_COMMAND_CAVEAT);
}

/**
 * The chat item for a message, or null when it is not conversation: not a
 * user/assistant message, a sub-agent's, synthetic, replayed or flagged as
 * metadata, no text (a tool-result-only user message), or a user entry that
 * opens with a WRAPPER_TAGS tag or the local-command caveat.
 * @param {ChatSource} m @returns {import("./types.js").HistoryItem | null}
 */
export function chatItem(m) {
  if (m.type !== "user" && m.type !== "assistant") return null;
  if (isMetadata(m)) return null;
  const c = m.message?.content;
  const text =
    typeof c === "string"
      ? c
      : (c ?? [])
          .filter((b) => b.type === "text")
          .map((b) => b.text)
          .join("\n");
  const t = (text ?? "").trim();
  if (!t || (m.type === "user" && isUserWrapper(t))) return null;
  return { role: m.type, text: t };
}

/**
 * The last CHAT_WINDOW items, in order.
 * @template T @param {T[]} items @returns {T[]}
 */
export function lastChatItems(items) {
  return items.slice(-CHAT_WINDOW);
}

/**
 * The chat items of a stored transcript: the last CHAT_WINDOW by time, each
 * message once. A compact writes older entries again at the end of the file
 * (same `uuid`, same `timestamp`), so the position in the file is not the
 * order of the conversation. An entry with no timestamp stays after the entry
 * it follows in the file.
 * @param {ChatSource[]} entries in file order
 * @returns {import("./types.js").HistoryItem[]}
 */
export function historyItems(entries) {
  /** @type {Set<string>} */
  const seen = new Set();
  /** @type {Array<{ at: string, item: import("./types.js").HistoryItem }>} */
  const rows = [];
  let at = "";
  for (const e of entries) {
    if (typeof e.timestamp === "string") at = e.timestamp;
    if (e.uuid) {
      if (seen.has(e.uuid)) continue;
      seen.add(e.uuid);
    }
    const item = chatItem(e);
    if (item) rows.push({ at, item });
  }
  // Array.prototype.sort is stable: equal times keep the file order.
  rows.sort((a, b) => (a.at < b.at ? -1 : a.at > b.at ? 1 : 0));
  return lastChatItems(rows.map((r) => r.item));
}
